"""The database schema, read from the database itself - never from a model's memory of it.

Why: a schema is the one kind of "knowledge" that has a source of truth. Letting the agent remember it
in free text (and then trusting that text) produced facts like "sales contains only id, date,
product_line, region, revenue" - missing `units` - which later runs believed. Here the schema is
generated by code, cached briefly, injected into the data-analyst prompt, and labelled authoritative.
"""

from __future__ import annotations

import asyncio
import threading
import time
from dataclasses import dataclass, field
from typing import Optional

from sqlalchemy import inspect

from open_deep_research.sql_guard import get_readonly_engine


@dataclass
class Schema:
    tables: dict[str, list[tuple[str, str]]] = field(default_factory=dict)   # table -> [(column, type)]
    primary_keys: dict[str, list[str]] = field(default_factory=dict)
    foreign_keys: list[str] = field(default_factory=list)
    read_at: float = field(default_factory=time.time)

    @property
    def identifiers(self) -> set[str]:
        out = set(self.tables)
        for cols in self.tables.values():
            out.update(c for c, _ in cols)
        return {i.lower() for i in out}

    def render(self) -> str:
        lines = []
        for table, cols in sorted(self.tables.items()):
            pk = set(self.primary_keys.get(table, []))
            body = ", ".join(f"{c} {t}{' PK' if c in pk else ''}" for c, t in cols)
            lines.append(f"- {table}({body})")
        lines += [f"- FK: {fk}" for fk in self.foreign_keys]
        return "\n".join(lines)


def read_schema(db_url: str) -> Schema:
    """Introspect through the READ-ONLY engine (same safety boundary as sql_executor)."""
    insp = inspect(get_readonly_engine(db_url))
    schema = Schema()
    for table in insp.get_table_names():
        schema.tables[table] = [(c["name"], str(c["type"])) for c in insp.get_columns(table)]
        schema.primary_keys[table] = list(insp.get_pk_constraint(table).get("constrained_columns") or [])
        for fk in insp.get_foreign_keys(table):
            schema.foreign_keys.append(
                f"{table}({', '.join(fk['constrained_columns'])}) -> {fk['referred_table']}({', '.join(fk['referred_columns'])})")
    return schema


_lock = threading.Lock()
_cache: dict[str, tuple[float, Schema]] = {}


def get_schema(db_url: str, ttl_s: float = 300.0, clock=time.monotonic) -> Schema:
    with _lock:
        hit = _cache.get(db_url)
        if hit and clock() - hit[0] < ttl_s:
            return hit[1]
    schema = read_schema(db_url)
    with _lock:
        _cache[db_url] = (clock(), schema)
    return schema


def reset_schema_cache() -> None:
    with _lock:
        _cache.clear()


UNAVAILABLE = ("(the schema could not be read automatically - discover it with sqlite_master / "
               "pragma_table_info('<table>') or information_schema before writing queries)")


async def schema_prompt_block(db_url: Optional[str], ttl_s: float = 300.0) -> str:
    """Text for the prompt; never raises (a broken database must not stop the agent from explaining it)."""
    if not db_url:
        return UNAVAILABLE
    try:
        schema = await asyncio.to_thread(get_schema, db_url, ttl_s)
        if not schema.tables:
            return UNAVAILABLE
        return schema.render()
    except Exception:
        return UNAVAILABLE
